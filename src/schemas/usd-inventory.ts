import { z } from 'zod'

/**
 * Finance v2 inventory (migration 000059, docs/ACCOUNTING_POLICY.md): fee
 * rules, fee-aware purchases, outflows and reversals. Platform-only.
 */

/**
 * Banks, by the code fee rules match on. One list for the supplier dialog,
 * the purchase dialog and the server, so the three can't disagree. DBBL is
 * Dutch-Bangla. Add a bank here, no migration needed.
 */
export const BANK_INSTITUTIONS = [
  { code: 'DBBL', name: 'Dutch-Bangla Bank' },
  { code: 'BRAC', name: 'BRAC Bank' },
  { code: 'IBBL', name: 'Islami Bank' },
  { code: 'UCB', name: 'United Commercial Bank' },
  { code: 'CITY', name: 'City Bank' },
  { code: 'EBL', name: 'Eastern Bank' },
  { code: 'SCB', name: 'Standard Chartered' },
  { code: 'PRIME', name: 'Prime Bank' },
] as const
export type BankCode = (typeof BANK_INSTITUTIONS)[number]['code']
const BANK_CODES = BANK_INSTITUTIONS.map((b) => b.code) as [BankCode, ...Array<BankCode>]

/** Paid in cash: there is no bank transfer, so no bank fee leg. */
export const PAID_IN_CASH = 'CASH'

export function bankName(code: string | null | undefined): string {
  if (!code) return '—'
  if (code === PAID_IN_CASH) return 'Cash'
  return BANK_INSTITUTIONS.find((b) => b.code === code)?.name ?? code
}

export const bankCode = z.enum(BANK_CODES, { message: 'Choose a bank' })

const usd = z.coerce
  .number({ message: 'Enter a valid USD amount' })
  .positive('Must be greater than zero')
  .max(1_000_000_000, 'Amount is too large')
  .refine((v) => Math.abs(v * 100 - Math.round(v * 100)) < 1e-6, 'Use whole cents')

const bdt = z.coerce
  .number({ message: 'Enter a valid BDT amount' })
  .positive('Must be greater than zero')
  .max(1_000_000_000_000, 'Amount is too large')

const reason = z.string().trim().min(1, 'Give a reason').max(500, 'Keep it under 500 characters')

const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max, `Keep it under ${max} characters`)
    .optional()
    .transform((v) => (v ? v : undefined))

const isoDateTime = z.iso.datetime({ offset: true, message: 'Enter a valid date and time' })
const isoDate = z.iso.date({ message: 'Enter a valid date' })

/** A fee typed in by hand (Payoneer, a route with no rule) or an override of
 * a rule's figure. Shares are checked again in the engine and the database. */
export const manualFeeSchema = z.object({
  total: z.coerce.number().min(0, 'Fee cannot be negative'),
  your_share: z.coerce.number().min(0, 'Your share cannot be negative'),
  reason,
})
export type ManualFeeInput = z.infer<typeof manualFeeSchema>

export const usdPurchaseDraftSchema = z.object({
  source_id: z.uuid('Choose a source'),
  /** Your bank the BDT left from, or CASH. */
  paid_from: z.union([bankCode, z.literal(PAID_IN_CASH)]),
  gross_usd: usd,
  bdt_principal: bdt,
  purchased_at: isoDateTime,
  bank_fee: manualFeeSchema.optional(),
  usd_fee: manualFeeSchema.optional(),
})
export type UsdPurchaseDraft = z.infer<typeof usdPurchaseDraftSchema>

export const usdPurchasePostSchema = usdPurchaseDraftSchema.extend({
  method: optionalText(100),
  external_reference: optionalText(120),
  notes: optionalText(1000),
})
export type UsdPurchasePostInput = z.infer<typeof usdPurchasePostSchema>

export const OUTFLOW_KINDS = ['META_BILL_PAYMENT', 'META_PREPAID_FUNDING', 'OPENING_ADJUSTMENT', 'OTHER'] as const
export type OutflowKind = (typeof OUTFLOW_KINDS)[number]
export const OUTFLOW_KIND_LABELS: Record<OutflowKind, string> = {
  META_BILL_PAYMENT: 'Meta bill paid',
  META_PREPAID_FUNDING: 'Prepaid Meta funding',
  OPENING_ADJUSTMENT: 'Opening adjustment',
  OTHER: 'Other',
}

export const usdOutflowPostSchema = z
  .object({
    kind: z.enum(['META_BILL_PAYMENT', 'META_PREPAID_FUNDING', 'OTHER']),
    usd_amount: usd,
    event_at: isoDateTime,
    ad_account_id: z.uuid().optional(),
    notes: optionalText(1000),
    /** Generated by the dialog once per open, so a double-click or retry posts
     * once. */
    idempotency_key: z.string().trim().min(8).max(100),
  })
  .refine((v) => v.kind === 'OTHER' || !!v.ad_account_id, {
    message: 'Choose the ad account',
    path: ['ad_account_id'],
  })
  .refine((v) => v.kind !== 'OTHER' || !!v.notes, {
    message: 'Say what this outflow was',
    path: ['notes'],
  })

export const openingStockSchema = z.object({
  /** USD actually on hand across every wallet at cut-over. */
  on_hand_usd: z.coerce.number().min(0, 'Cannot be negative'),
  as_of: isoDateTime,
  notes: reason,
})

export const reversalSchema = z.object({ id: z.uuid(), reason })

export const FEE_CHANNELS = ['BANK_INTERNAL', 'NPSB', 'BINANCE', 'PAYONEER'] as const
export const FEE_CHANNEL_LABELS: Record<(typeof FEE_CHANNELS)[number], string> = {
  BANK_INTERNAL: 'Same-bank transfer',
  NPSB: 'NPSB (bank to another bank)',
  BINANCE: 'Binance',
  PAYONEER: 'Payoneer',
}

export const feeRuleCreateSchema = z
  .object({
    code: z.string().trim().min(1, 'Give the rule a short name').max(60),
    channel: z.enum(FEE_CHANNELS),
    from_institution: z.string().trim().min(1).max(20),
    to_institution: z.string().trim().min(1).max(20),
    fee_type: z.enum(['FIXED', 'PERCENT']),
    amount: z.coerce.number().min(0).optional(),
    percent: z.coerce.number().min(0).max(100).optional(),
    currency: z.enum(['BDT', 'USD']),
    your_share_pct: z.coerce.number().min(0).max(100),
    effective_from: isoDate,
    notes: optionalText(500),
  })
  .refine((v) => (v.fee_type === 'FIXED' ? v.amount != null : v.percent != null), {
    message: 'Enter the fee',
    path: ['amount'],
  })

export const feeRuleEndSchema = z.object({ id: z.uuid(), effective_to: isoDate })

