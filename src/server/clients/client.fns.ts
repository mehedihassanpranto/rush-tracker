/** Client list row with active-account count and current due (BDT + USD approx). */
export interface ClientListItem extends Client {
  active_accounts: number
  current_due: string
  current_due_usd: string
}

export const listClientsFn = createServerFn({ method: 'GET' }).handler(
  async (): Promise<Array<ClientListItem>> => {
    await requireAdmin(PERMISSIONS.CLIENTS_VIEW)
    const admin = getSupabaseAdminClient()

    const { data: clients, error } = await admin
      .from('clients')
      .select('*')
      .order('created_at', { ascending: false })
    if (error) throw new Error(error.message)

    const { data: activeAssignments } = await admin
      .from('ad_account_assignments')
      .select('client_id')
      .eq('status', 'ACTIVE')

    const counts = new Map<string, number>()
    for (const row of activeAssignments ?? []) {
      const id = (row as { client_id: string }).client_id
      counts.set(id, (counts.get(id) ?? 0) + 1)
    }

    // Current due per client, ledger-derived (spec §35). Best-effort: if the
    // aggregate isn't available, the list still renders with 0 dues.
    const dueByClient = new Map<string, string>()
    const { data: dueRows } = await admin.rpc('all_client_dues')
    for (const r of (dueRows ?? []) as Array<{
      client_id: string
      current_due: string | number
    }>) {
      dueByClient.set(r.client_id, String(r.current_due))
    }

    const rate = await currentUsdRate()

    return (clients as Array<Client>).map((c) => {
      const dueBdt = dueByClient.get(c.id) ?? '0'
      return {
        ...c,
        active_accounts: counts.get(c.id) ?? 0,
        current_due: dueBdt,
        current_due_usd: bdtToUsd(dueBdt, rate),
      }
    })
  },
)

export const getClientFn = createServerFn({ method: 'GET' })
  .validator(z.object({ id: z.uuid() }))
  .handler(async ({ data }): Promise<Client> => {
    await requireAdmin(PERMISSIONS.CLIENTS_VIEW)
    const admin = getSupabaseAdminClient()
    const { data: client, error } = await admin
      .from('clients')
      .select('*')
      .eq('id', data.id)
      .single()
    if (error) throw new Error(error.message)
    return client as Client
  })

export const createClientFn = createServerFn({ method: 'POST' })
  .validator(clientCreateSchema)
  .handler(async ({ data }): Promise<Client> => {
    const actor = await requireAdmin(PERMISSIONS.CLIENTS_MANAGE)
    const admin = getSupabaseAdminClient()

    // client_code is auto-generated by the DB default (CL-000N).
    const { data: client, error } = await admin
      .from('clients')
      .insert({
        name: data.name,
        company_name: data.company_name ?? null,
        email: data.email ?? null,
        phone: data.phone ?? null,
        address: data.address ?? null,
        status: data.status,
      })
      .select('*')
      .single()
    if (error) throw new Error(error.message)

    await writeAudit({
      actorUserId: actor.id,
      action: 'CLIENT_CREATED',
      entityType: 'CLIENT',
      entityId: client.id,
      newValues: client,
    })
    return client as Client
  })

export const updateClientFn = createServerFn({ method: 'POST' })
