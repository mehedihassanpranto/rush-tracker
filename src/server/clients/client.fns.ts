/**
 * Delete a client — ONLY when it has no financial or account history
 * (spec §7 lists deactivate, not delete; approved financial records are
 * immutable and must never be orphaned). Clients with any ledger entry,
 * payment, payment request, limit request, or account assignment cannot be
 * deleted and must be deactivated instead. Safe to remove a client that was
 * created by mistake and never used.
 */
export const deleteClientFn = createServerFn({ method: 'POST' })
  .validator(z.object({ id: z.uuid() }))
  .handler(async ({ data }): Promise<{ ok: true }> => {
    const actor = await requireAdmin(PERMISSIONS.CLIENTS_MANAGE)
    const admin = getSupabaseAdminClient()

    const { data: client } = await admin
      .from('clients')
      .select('id, client_code, name')
      .eq('id', data.id)
      .single()
    if (!client) throw new Error('Client not found')

    // Block deletion when any history references this client.
    const historyTables = [
      { table: 'ledger_entries', label: 'ledger entries' },
      { table: 'payments', label: 'payments' },
      { table: 'payment_requests', label: 'payment requests' },
      { table: 'limit_requests', label: 'limit requests' },
      { table: 'ad_account_assignments', label: 'account assignments' },
      { table: 'adjustments', label: 'adjustments' },
    ] as const

    const counts = await Promise.all(
      historyTables.map(({ table }) =>
        admin
          .from(table)
          .select('id', { count: 'exact', head: true })
          .eq('client_id', data.id),
      ),
    )
    const blockers = historyTables
      .map((t, i) => ({ label: t.label, count: counts[i].count ?? 0 }))
      .filter((t) => t.count > 0)
    if (blockers.length > 0) {
      const detail = blockers.map((b) => `${b.count} ${b.label}`).join(', ')
      throw new Error(
        `This client has history (${detail}) and cannot be deleted. Deactivate it instead to preserve the financial record.`,
      )
    }

    // Collect the client's login user ids before the membership rows cascade.
    const { data: memberships } = await admin
      .from('client_memberships')
      .select('user_id')
      .eq('client_id', data.id)
    const loginUserIds = [
      ...new Set(
        ((memberships ?? []) as Array<{ user_id: string }>).map(
          (m) => m.user_id,
        ),
      ),
    ]

    // Delete the client (client_memberships for this client cascade away).
    const { error: delErr } = await admin
      .from('clients')
      .delete()
      .eq('id', data.id)
    if (delErr) throw new Error(delErr.message)

    // Clean up now-orphaned CLIENT logins that belong to no other client.
    for (const userId of loginUserIds) {
      const { count } = await admin
        .from('client_memberships')
        .select('client_id', { count: 'exact', head: true })
        .eq('user_id', userId)
      if ((count ?? 0) === 0) {
        await admin.auth.admin.deleteUser(userId)
      }
    }

    await writeAudit({
      actorUserId: actor.id,
      action: 'CLIENT_DELETED',
      entityType: 'CLIENT',
      entityId: data.id,
      oldValues: client,
    })
    return { ok: true }
  })

export interface ClientUserRow {
  user_id: string
  full_name: string
  email: string
  membership_status: 'ACTIVE' | 'INACTIVE'
}

export const listClientUsersFn = createServerFn({ method: 'GET' })
  .validator(z.object({ client_id: z.uuid() }))
  .handler(async ({ data }): Promise<Array<ClientUserRow>> => {
    await requireAdmin(PERMISSIONS.CLIENTS_VIEW)
    const admin = getSupabaseAdminClient()

    const { data: memberships, error } = await admin
      .from('client_memberships')
      .select('user_id, status, profile:user_profiles(full_name)')
      .eq('client_id', data.client_id)
    if (error) throw new Error(error.message)

    const rows = (memberships ?? []) as unknown as Array<{
      user_id: string
      status: 'ACTIVE' | 'INACTIVE'
      profile: { full_name: string } | null
    }>

    // Emails live in auth.users — fetch via the admin API per user.
    const result: Array<ClientUserRow> = []
    for (const m of rows) {
      const { data: userRes } = await admin.auth.admin.getUserById(m.user_id)
      result.push({
        user_id: m.user_id,
        full_name: m.profile?.full_name ?? '',
        email: userRes.user?.email ?? '',
        membership_status: m.status,
      })
    }
    return result
  })

/**
 * Provision a new CLIENT login and link it to this client (spec §12, §57).
 * The login is created with app_role=CLIENT in app_metadata (server-only),
 * email pre-confirmed, and an ACTIVE membership row.
 */
export const createClientUserFn = createServerFn({ method: 'POST' })
  .validator(clientUserCreateSchema)
  .handler(async ({ data }): Promise<{ user_id: string }> => {
    const actor = await requireAdmin(PERMISSIONS.CLIENTS_MANAGE)
    const admin = getSupabaseAdminClient()

    const { data: created, error } = await admin.auth.admin.createUser({
      email: data.email,
      password: data.password,
      email_confirm: true,
      app_metadata: { app_role: 'CLIENT' },
      user_metadata: { full_name: data.full_name },
    })
    if (error) throw new Error(error.message)
    const userId = created.user.id

    // The on_auth_user_created trigger creates the profile; ensure the name.
    await admin
      .from('user_profiles')
      .update({ full_name: data.full_name })
      .eq('user_id', userId)

    const { error: memErr } = await admin
      .from('client_memberships')
      .insert({ user_id: userId, client_id: data.client_id, status: 'ACTIVE' })
    if (memErr) throw new Error(memErr.message)

    await writeAudit({
      actorUserId: actor.id,
      action: 'CLIENT_USER_CREATED',
      entityType: 'CLIENT',
      entityId: data.client_id,
      newValues: { user_id: userId, email: data.email },
    })
    return { user_id: userId }
  })
